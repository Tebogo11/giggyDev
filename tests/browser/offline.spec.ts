test('packaged runtime lazy-loads inspector with isolated styles and stays inert without dev flag', async ({ page }) => {
  await page.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.origin !== 'http://library.test') return route.abort();
    if (url.pathname === '/') {
      return route.fulfill({ contentType: 'text/html', body: `<html><head><title>Library fixture</title></head><body><script>window.originalLog=console.log</script><script type="module" src="/__giggydev/client.js${url.search}"></script></body></html>` });
    }
    const filename = url.pathname.replace('/__giggydev/', '');
    if (!/^(client\.js|chunks\/[\w-]+\.js)$/.test(filename)) return route.fulfill({ status: 404 });
    const code = await readFile(resolve('dist', filename), 'utf8');
    const flag = filename === 'client.js' ? `const __GIGGY_DEV__ = ${url.searchParams.get('disabled') !== '1'};\n` : '';
    return route.fulfill({ contentType: 'text/javascript', body: flag + code });
  });
  await page.goto('http://library.test');
  await expect(page.getByRole('button', { name: 'Open giggyDev' })).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.evaluate(() => console.warn('Captured before inspector loaded'));
  await page.getByRole('button', { name: 'Open giggyDev' }).click();
  await page.getByRole('button', { name: 'Console', exact: true }).click();
  await expect(page.locator('.entry')).toContainText('Captured before inspector loaded');
  expect(await page.locator('#giggydev-host').locator('style[data-styled]').count()).toBeGreaterThan(0);
  expect(await page.evaluate(() => document.head.querySelector('style[data-styled]'))).toBeNull();
  await page.goto('http://library.test/?disabled=1');
  await expect(page.locator('#giggydev-host')).toHaveCount(0);
  expect(await page.evaluate('console.log === window.originalLog')).toBe(true);
});

